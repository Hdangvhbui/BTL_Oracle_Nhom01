-- Bảng 1: LOAISANPHAM
CREATE TABLE LOAISANPHAM (
    MALOAI VARCHAR2(20 CHAR) PRIMARY KEY,
    TENLOAI NVARCHAR2(100) NOT NULL UNIQUE,
    MOTA NVARCHAR2(255)
);

-- Bảng 2: SANPHAM (Quản lý theo từng SKU: màu + size)
CREATE TABLE SANPHAM (
    MASP VARCHAR2(20 CHAR) PRIMARY KEY,
    TENSP NVARCHAR2(150) NOT NULL,
    KICHCO VARCHAR2(10 CHAR) NOT NULL,
    MAUSAC NVARCHAR2(50) NOT NULL,
    CHATLIEU NVARCHAR2(100) NOT NULL,
    GIABAN NUMBER(15,0) NOT NULL,
    SOLUONGTON NUMBER(10,0) DEFAULT 0 NOT NULL,
    MALOAI VARCHAR2(20 CHAR) NOT NULL,
    CONSTRAINT FK_SP_LOAI FOREIGN KEY (MALOAI) REFERENCES LOAISANPHAM(MALOAI),
    CONSTRAINT CK_SP_SIZE CHECK (KICHCO IN ('S', 'M', 'L', 'XL', 'XXL')),
    CONSTRAINT CK_SP_GIABAN CHECK (GIABAN > 0),
    CONSTRAINT CK_SP_TON CHECK (SOLUONGTON >= 0)
);

-- Bảng 3: NHACUNGCAP
CREATE TABLE NHACUNGCAP (
    MANCC VARCHAR2(20 CHAR) PRIMARY KEY,
    TENNCC NVARCHAR2(150) NOT NULL,
    DIACHI NVARCHAR2(200),
    SDT VARCHAR2(15 CHAR) NOT NULL UNIQUE,
    EMAIL VARCHAR2(100)
);

-- Bảng 4: NHANVIEN
CREATE TABLE NHANVIEN (
    MANV VARCHAR2(20 CHAR) PRIMARY KEY,
    HOTEN NVARCHAR2(100) NOT NULL,
    NGAYSINH DATE,
    GIOITINH NVARCHAR2(10),
    SDT VARCHAR2(15 CHAR) UNIQUE,
    CHUCVU NVARCHAR2(50) NOT NULL,
    LUONG NUMBER(15,0) NOT NULL,
    CONSTRAINT CK_NV_LUONG CHECK (LUONG > 0)
);

-- Bảng 5: KHACHHANG
CREATE TABLE KHACHHANG (
    MAKH VARCHAR2(20 CHAR) PRIMARY KEY,
    HOTEN NVARCHAR2(100) NOT NULL,
    SDT VARCHAR2(15 CHAR) NOT NULL UNIQUE,
    DIACHI NVARCHAR2(200)
);

-- Bảng 6: PHIEUNHAP (Không lưu tổng tiền thừa)
CREATE TABLE PHIEUNHAP (
    MAPN VARCHAR2(20 CHAR) PRIMARY KEY,
    NGAYNHAP DATE DEFAULT SYSDATE NOT NULL,
    MANCC VARCHAR2(20 CHAR) NOT NULL,
    MANV VARCHAR2(20 CHAR) NOT NULL,
    CONSTRAINT FK_PN_NCC FOREIGN KEY (MANCC) REFERENCES NHACUNGCAP(MANCC),
    CONSTRAINT FK_PN_NV FOREIGN KEY (MANV) REFERENCES NHANVIEN(MANV)
);

-- Bảng 7: CT_PHIEUNHAP
CREATE TABLE CT_PHIEUNHAP (
    MAPN VARCHAR2(20 CHAR),
    MASP VARCHAR2(20 CHAR),
    SOLUONGNHAP NUMBER(10,0) NOT NULL,
    GIANHAP NUMBER(15,0) NOT NULL,
    CONSTRAINT PK_CTPN PRIMARY KEY (MAPN, MASP),
    CONSTRAINT FK_CTPN_PN FOREIGN KEY (MAPN) REFERENCES PHIEUNHAP(MAPN),
    CONSTRAINT FK_CTPN_SP FOREIGN KEY (MASP) REFERENCES SANPHAM(MASP),
    CONSTRAINT CK_CTPN_SL CHECK (SOLUONGNHAP > 0),
    CONSTRAINT CK_CTPN_GIA CHECK (GIANHAP > 0)
);

-- Bảng 8: HOADON (Khách lẻ được phép NULL MAKH)
CREATE TABLE HOADON (
    MAHD VARCHAR2(20 CHAR) PRIMARY KEY,
    NGAYLAP DATE DEFAULT SYSDATE NOT NULL,
    MANV VARCHAR2(20 CHAR) NOT NULL,
    MAKH VARCHAR2(20 CHAR),
    CONSTRAINT FK_HD_NV FOREIGN KEY (MANV) REFERENCES NHANVIEN(MANV),
    CONSTRAINT FK_HD_KH FOREIGN KEY (MAKH) REFERENCES KHACHHANG(MAKH)
);

-- Bảng 9: CT_HOADON (THANHTIEN là cột ảo tự tính)
CREATE TABLE CT_HOADON (
    MAHD VARCHAR2(20 CHAR),
    MASP VARCHAR2(20 CHAR),
    SOLUONGBAN NUMBER(10,0) NOT NULL,
    DONGIABAN NUMBER(15,0) NOT NULL,
    THANHTIEN NUMBER(15,0) GENERATED ALWAYS AS (SOLUONGBAN * DONGIABAN),
    CONSTRAINT PK_CTHD PRIMARY KEY (MAHD, MASP),
    CONSTRAINT FK_CTHD_HD FOREIGN KEY (MAHD) REFERENCES HOADON(MAHD),
    CONSTRAINT FK_CTHD_SP FOREIGN KEY (MASP) REFERENCES SANPHAM(MASP),
    CONSTRAINT CK_CTHD_SL CHECK (SOLUONGBAN > 0),
    CONSTRAINT CK_CTHD_GIA CHECK (DONGIABAN > 0)
);

