-- 1. Bật cờ cho phép tạo user thường
ALTER SESSION SET "_ORACLE_SCRIPT"=true;

-- 2. Tạo 2 Tablespace: DATA (chứa dữ liệu thật) và LAB (để bạn An làm bài lab xóa/dời file)
CREATE TABLESPACE TBS_FASHION_DATA
DATAFILE 'D:\oracle_btl\FASHION_DATA01.DBF' 
SIZE 50M AUTOEXTEND ON NEXT 10M MAXSIZE 500M
EXTENT MANAGEMENT LOCAL AUTOALLOCATE;

CREATE TABLESPACE TBS_FASHION_LAB
DATAFILE 'D:\oracle_btl\FASHION_LAB01.DBF' 
SIZE 20M AUTOEXTEND OFF;

-- 3. Tạo User chủ sở hữu CSDL (FASHION_ADMIN)
CREATE USER FASHION_ADMIN IDENTIFIED BY Admin123456
DEFAULT TABLESPACE TBS_FASHION_DATA
QUOTA UNLIMITED ON TBS_FASHION_DATA;

GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE TO FASHION_ADMIN;

-- 4. Tạo User dành riêng cho kết nối Web
CREATE USER FASHION_WEB IDENTIFIED BY WebPass123
DEFAULT TABLESPACE TBS_FASHION_DATA;

GRANT CREATE SESSION TO FASHION_WEB;

-- 5. Tạo 2 User nghiệp vụ để bạn Dũng kiểm thử phân quyền
CREATE USER NV_THUNGAN IDENTIFIED BY ThuNgan123 DEFAULT TABLESPACE TBS_FASHION_DATA;
CREATE USER NV_THUKHO IDENTIFIED BY ThuKho123 DEFAULT TABLESPACE TBS_FASHION_DATA;
GRANT CREATE SESSION TO NV_THUNGAN, NV_THUKHO;


ALTER SESSION SET "_ORACLE_SCRIPT"=true;
ALTER USER FASHION_ADMIN IDENTIFIED BY "Hdangdz.vcl1";