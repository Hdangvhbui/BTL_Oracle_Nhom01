-- DÒNG QUAN TRỌNG NHẤT: Mở khóa tạo User/Role không cần tiền tố C## trong Oracle 19c
ALTER SESSION SET "_ORACLE_SCRIPT"=TRUE;

-- 1. Tạo 2 Role nghiệp vụ
CREATE ROLE ROLE_THUNGAN;
CREATE ROLE ROLE_THUKHO;

-- 2. Cấp quyền cho ROLE_THUNGAN
GRANT CREATE SESSION TO ROLE_THUNGAN;
GRANT SELECT ON FASHION_ADMIN.SANPHAM TO ROLE_THUNGAN;
GRANT SELECT, INSERT ON FASHION_ADMIN.HOADON TO ROLE_THUNGAN;
GRANT SELECT, INSERT ON FASHION_ADMIN.CT_HOADON TO ROLE_THUNGAN;

-- 3. Cấp quyền cho ROLE_THUKHO
GRANT CREATE SESSION TO ROLE_THUKHO;
GRANT SELECT, UPDATE(SOLUONGTON) ON FASHION_ADMIN.SANPHAM TO ROLE_THUKHO;
GRANT SELECT, INSERT ON FASHION_ADMIN.PHIEUNHAP TO ROLE_THUKHO;
GRANT SELECT, INSERT ON FASHION_ADMIN.CT_PHIEUNHAP TO ROLE_THUKHO;

-- 4. Tạo User và gán Role tương ứng
CREATE USER NV_THUNGAN IDENTIFIED BY ThuNgan123;
GRANT ROLE_THUNGAN TO NV_THUNGAN;

CREATE USER NV_THUKHO IDENTIFIED BY ThuKho123;
GRANT ROLE_THUKHO TO NV_THUKHO;